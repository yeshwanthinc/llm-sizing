function buildMarkdownReport(r) {
  const lines = [
    `# LLM GPU Capacity Sizing — ${r.modelKey || 'Custom model'} on ${r.numGPUs}× ${r.gpuKey || 'GPU'}`,
    '',
    `| Setting | Value |`,
    `|---|---|`,
    `| Model | ${r.modelKey || 'Custom'} (${r.params_B}B params${r.isMoE ? `, ${r.activeP_B}B active` : ''}) |`,
    `| GPU | ${r.numGPUs}× ${r.gpuKey || 'Custom'} (${r.nodeCount} node${r.nodeCount>1?'s':''}) |`,
    `| Precision | weights ${r.prec.toUpperCase()} / KV ${r.kvPrec.toUpperCase()} |`,
    `| RPS | ${r.rps} (${r.inTok} in / ${r.outTok} out tokens) |`,
    '',
    `## Results`,
    '',
    `| Metric | Value |`,
    `|---|---|`,
    `| Spare Capacity | ${r.spareCapPct.toFixed(1)}% |`,
    `| Max RPS | ${fmtK(r.maxRPS)} |`,
    `| Bottleneck | ${r.bottleneck} |`,
    `| Memory Utilization | ${pct(r.memUtil)} |`,
    `| Prefill Compute Utilization | ${pct(r.prefillUtil)} |`,
    `| Decode Throughput Utilization | ${pct(r.decodeUtil)} |`,
    `| Time to First Token | ${fmtMs(r.ttft)} |`,
    `| Time Between Tokens | ${fmtMs(r.tbt)} |`,
    `| End-to-End Latency | ${fmtMs(r.e2eLatency)} |`,
    `| Total GPU Memory | ${fmtGB(r.totalMemGB)} |`,
    `| Model Weights | ${fmtGB(r.modelMemGB)} |`,
    `| KV Cache Used | ${fmtGB(r.requiredKVGB)} |`,
    `| Cost / hour | $${r.costPerHr.toFixed(2)}${r.spotEnabled?' (spot)':''} |`,
    `| Cost / 1M output tokens | $${r.costPerMTok.toFixed(2)} |`,
    '',
    `_Generated by the LLM GPU Capacity Sizing Calculator._`,
  ];
  return lines.join('\n');
}

function exportMarkdown() {
  if (!lastResult) { alert('Click Calculate first.'); return; }
  copyToClipboard(buildMarkdownReport(lastResult)).then(() => showToast('📋 Markdown copied to clipboard'));
}

function exportJSON() {
  if (!lastResult) { alert('Click Calculate first.'); return; }
  downloadFile('llm-sizing-result.json', JSON.stringify(lastResult, null, 2), 'application/json');
  showToast('⬇ JSON downloaded');
}

function exportPNG() {
  if (!lastResult) { alert('Click Calculate first.'); return; }
  if (typeof html2canvas !== 'function') { alert('PNG export library failed to load.'); return; }
  html2canvas(g('main-area'), { backgroundColor: '#0d1117' }).then(canvas => {
    const a = document.createElement('a');
    a.download = 'llm-sizing-dashboard.png';
    a.href = canvas.toDataURL('image/png');
    a.click();
    showToast('🖼 PNG downloaded');
  }).catch(() => alert('PNG export failed — try Copy Markdown or Download JSON instead.'));
}
